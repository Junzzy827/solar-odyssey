const deg = (x: number) => ((x % 360) + 360) % 360

/** その日時（世界時のミリ秒）の、地球から見た月。黄経・黄緯（ラジアン、その日の春分点が基準）と距離（km） */
export function moonEcliptic(ms: number) {
  const T = centuries(ms)
  const Lp = deg(218.3164477 + 481267.88123421 * T - 0.0015786 * T * T + (T * T * T) / 538841)
  const D = deg(297.8501921 + 445267.1114034 * T - 0.0018819 * T * T + (T * T * T) / 545868)
  const M = deg(357.5291092 + 35999.0502909 * T - 0.0001536 * T * T)
  const Mp = deg(134.9633964 + 477198.8675055 * T + 0.0087414 * T * T + (T * T * T) / 69699)
  const F = deg(93.272095 + 483202.0175233 * T - 0.0036539 * T * T - (T * T * T) / 3526000)
  const A1 = deg(119.75 + 131.849 * T)
  const A2 = deg(53.09 + 479264.29 * T)
  const A3 = deg(313.45 + 481266.484 * T)
  const E = 1 - 0.002516 * T - 0.0000074 * T * T
  let sl = 0
  let sr = 0
  for (const [d, m, mp, f, l, r] of LR) {
    const arg = (d * D + m * M + mp * Mp + f * F) * DEG
    const e = Math.abs(m) === 1 ? E : Math.abs(m) === 2 ? E * E : 1
    sl += l * e * Math.sin(arg)
    sr += r * e * Math.cos(arg)
  }
  let sb = 0
  for (const [d, m, mp, f, b] of B) {
    const e = Math.abs(m) === 1 ? E : Math.abs(m) === 2 ? E * E : 1
    sb += b * e * Math.sin((d * D + m * M + mp * Mp + f * F) * DEG)
  }
  sl += 3958 * Math.sin(A1 * DEG) + 1962 * Math.sin((Lp - F) * DEG) + 318 * Math.sin(A2 * DEG)
  sb +=
    -2235 * Math.sin(Lp * DEG) +
    382 * Math.sin(A3 * DEG) +
    175 * Math.sin((A1 - F) * DEG) +
    175 * Math.sin((A1 + F) * DEG) +
    127 * Math.sin((Lp - Mp) * DEG) -
    115 * Math.sin((Lp + Mp) * DEG)
  return { lon: (Lp + sl / 1e6) * DEG, lat: (sb / 1e6) * DEG, km: 385000.56 + sr / 1000 }
}

/** その日時の、地球から見た太陽の黄経（ラジアン、その日の春分点が基準） */
export function sunLongitude(ms: number) {
  const T = centuries(ms)
  const L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T * T
  const M = (357.52911 + 35999.05029 * T - 0.0001537 * T * T) * DEG
  const C = (1.914602 - 0.004817 * T) * Math.sin(M) + (0.019993 - 0.000101 * T) * Math.sin(2 * M) + 0.000289 * Math.sin(3 * M)
  // 光が届くまでのあいだに地球が動く分（光行差、約20秒角）だけ、見える向きは少し後ろ
  return deg(L0 + C - 0.00569) * DEG
}

/** 2000年の春分点から、その日の春分点までずれた角度（歳差。100年で約1.4度） */
export const precession = (ms: number) => {
  const T = centuries(ms)
  return ((5029.0966 * T + 1.11113 * T * T) / 3600) * DEG
}

/** グリニッジ恒星時（ラジアン）：春分点から見た、グリニッジの経線の向き。地球の自転の角度に使う */
export function greenwichSiderealTime(ms: number) {
  const days = (ms - Date.UTC(2000, 0, 1, 12)) / DAY_MS
  const T = days / 36_525
  return deg(280.46061837 + 360.98564736629 * days + 0.000387933 * T * T) * DEG
}

/**
 * 日食・月食の影の位置。月の中心が、太陽と地球を結ぶ線からどれだけ離れているか（地球の半径が単位）。
 * along は太陽の向きに測った月までの距離（正なら月は太陽の側＝新月、負なら反対側＝満月）、
 * perp は線に直角な向きのずれ（その日の春分点が基準の、画面と同じ軸 x・上・-y）
 */
export function shadowGeometry(ms: number) {
  const m = moonEcliptic(ms)
  const s = sunLongitude(ms)
  const r = m.km / EARTH_RADIUS_KM
  const mx = r * Math.cos(m.lat) * Math.cos(m.lon)
  const my = r * Math.sin(m.lat)
  const mz = -r * Math.cos(m.lat) * Math.sin(m.lon)
  const sx = Math.cos(s)
  const sz = -Math.sin(s)
  const along = mx * sx + mz * sz
  const perp = { x: mx - along * sx, y: my, z: mz - along * sz }
  return { along, perp, gamma: Math.hypot(perp.x, perp.y, perp.z), moonKm: m.km }
}
